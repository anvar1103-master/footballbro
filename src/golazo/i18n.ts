/** translate a Russian source string (falls back to the source) */
export function tr(s: string): string {
  if (lang === 'ru' || !s) return s;
  const hit = EN[s];
  if (hit) return hit;
  const m = /^Пасы ×(\d+)$/.exec(s);
  if (m) return `Passes ×${m[1]}`;
  const f = /^Штрафной (\d+)$/.exec(s);
  if (f) return `Free kick ${f[1]}`;
  return s;
}
