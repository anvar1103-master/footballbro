/**
 * Two languages: Russian (source text, used as the key) and English. `tr()` looks a Russian string up and
 * returns the English one when the game runs in English; unknown strings fall back to Russian.
 */
export type Lang = 'ru' | 'en';
export let lang: Lang = 'ru';
export function setLang(l: Lang) {
  lang = l;
  try {
    document.documentElement.lang = l;
  } catch {
    /* no DOM */
  }
}

/** pick the game language from a Yandex / browser language code */
export function pickLang(code?: string | null): Lang {
  const c = (code ?? '').toLowerCase().slice(0, 2);
  return ['ru', 'be', 'kk', 'uk', 'uz', 'ky', 'tg', 'hy', 'az', 'tt'].includes(c) ? 'ru' : c ? 'en' : 'ru';
}

